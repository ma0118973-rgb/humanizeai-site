// Deep fallback: merge missing keys from English so incomplete languages never crash
function deepMerge(base: any, override: any): any {
  if (!override) return base;
  if (typeof base !== "object" || typeof override !== "object" || base === null) {
    return override !== undefined ? override : base;
  }
  if (Array.isArray(base)) {
    return Array.isArray(override) ? override : base;
  }
  const result: any = { ...base };
  for (const key of Object.keys(override)) {
    result[key] = deepMerge(base[key], override[key]);
  }
  return result;
}

// Apply fallback to all non-English languages
for (const lang of Object.keys(TRANSLATIONS)) {
  if (lang !== "en") {
    TRANSLATIONS[lang as keyof typeof TRANSLATIONS] = deepMerge(TRANSLATIONS.en, TRANSLATIONS[lang]) as any;
  }
}
